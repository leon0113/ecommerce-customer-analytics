"""Write reports/summary.xlsx: headline KPIs and the key analysis tables, one sheet each.

Every table comes from the same SQL queries and metric functions the notebooks use, so the
workbook and the notebooks cannot disagree. Run with: python -m src.export_summary
"""

from __future__ import annotations

import logging

import pandas as pd
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from src import metrics
from src.common import load_config, project_path, setup_logging

logger = logging.getLogger(__name__)

HEADER_FILL = PatternFill("solid", fgColor="2A78D6")
HEADER_FONT = Font(bold=True, color="FFFFFF")
AT_RISK_COLUMNS = [
    "customer_id", "full_name", "phone", "division", "acquisition_channel", "orders", "revenue",
    "last_order_date", "recency_days", "rfm_segment", "discount_share", "return_rate",
]


def definitions(cfg: dict, rule: dict[str, float]) -> pd.DataFrame:
    """Plain-language definitions of every metric in the workbook."""
    settings = cfg["analysis"]
    return pd.DataFrame(
        [
            ("Data", "Synthetic e-commerce data generated by src/generate_data.py; not real customers."),
            ("Period", f"{cfg['dates']['start']} to {cfg['dates']['end']}; snapshot date {settings['snapshot_date']}."),
            ("Net revenue", "Quantity x unit price x (1 - order discount), delivered orders only, in BDT."),
            ("Refunds", "Reported separately; not subtracted from net revenue."),
            ("Churned", f"No order for more than {rule['threshold_days']} days at the snapshot date "
                        f"(the {settings['churn_gap_quantile']:.0%} quantile of gaps between repeat orders)."),
            ("Too new", "First order within the churn threshold of the snapshot; excluded from churn rates."),
            ("At risk", f"Active, but silent for longer than the median repeat gap ({rule['median_gap_days']:.0f} days)."),
            ("RFM", "Recency and monetary scored in quintiles; frequency in fixed bins (1, 2, 3, 4-5, 6+ orders)."),
            ("Churn drivers", "Computed on repeat buyers only; one-order buyers are churned by definition."),
            ("Cohort", "Customers grouped by the quarter of their first delivered order."),
        ],
        columns=["term", "definition"],
    )


def build_sheets(cfg: dict) -> dict[str, pd.DataFrame]:
    """Compute every table that goes into the workbook."""
    settings = cfg["analysis"]
    with metrics.open_db(cfg) as conn:
        customers, rule = metrics.build_customer_table(conn, cfg)
        names = pd.read_sql_query("SELECT customer_id, full_name, phone FROM customers", conn)
        activity = metrics.run_query(conn, "customer_quarter_activity")
        kpis = metrics.run_query(conn, "kpi_summary").T.reset_index()
        kpis.columns = ["metric", "value"]
        extra_kpis = pd.DataFrame({
            "metric": ["top_20pct_buyer_revenue_share_pct", "churn_threshold_days", "churn_rate_judged_pct",
                       "at_risk_customers", "at_risk_revenue_bdt"],
            "value": [
                round(metrics.top_share(customers["revenue"], settings["pareto_top_share"]) * 100, 1),
                rule["threshold_days"],
                round(customers.loc[customers["churn_status"] != "too_new", "churned"].mean() * 100, 1),
                int(customers["at_risk"].sum()),
                round(customers.loc[customers["at_risk"], "revenue"].sum(), 2),
            ],
        })
        sheets = {
            "Definitions": definitions(cfg, rule),
            "KPIs": pd.concat([kpis, extra_kpis], ignore_index=True),
            "Yearly revenue": metrics.run_query(conn, "yearly_revenue"),
            "Monthly revenue": metrics.run_query(conn, "monthly_revenue"),
            "Categories": metrics.run_query(conn, "category_performance"),
            "Divisions": metrics.run_query(conn, "division_performance"),
            "Payment methods": metrics.run_query(conn, "payment_method_mix"),
        }

    repeat = customers[customers["orders"] > 1]
    drivers = pd.concat(
        {column: metrics.churn_rate_by(repeat, column) for column in
         ["discount_band", "return_band", "acquisition_channel", "division"]},
        names=["driver", "group"],
    ).reset_index()

    at_risk = customers[customers["at_risk"]].merge(names, on="customer_id")
    at_risk = at_risk.sort_values("revenue", ascending=False).head(settings["at_risk_top_n"])

    retention = metrics.retention_matrix(activity, settings["max_cohort_quarters"])
    retention.columns = [f"Q+{q}" for q in retention.columns]

    sheets |= {
        "RFM segments": metrics.segment_profile(customers).reset_index(),
        "Churn drivers": drivers,
        "At-risk customers": at_risk[AT_RISK_COLUMNS],
        "Cohort retention": retention.reset_index(),
        "Cleaning log": pd.read_csv(project_path(cfg["paths"]["processed_dir"]) / "cleaning_log.csv"),
    }
    return sheets


def format_sheet(worksheet) -> None:
    """Coloured bold header, frozen header row, sensible column widths and number formats."""
    for cell in worksheet[1]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    worksheet.freeze_panes = "A2"
    for column_cells in worksheet.columns:
        header = str(column_cells[0].value or "")
        width = max(len(header), *(len(str(c.value)) for c in column_cells[1:50] if c.value is not None), 8)
        worksheet.column_dimensions[get_column_letter(column_cells[0].column)].width = min(width + 2, 60)
        for cell in column_cells[1:]:
            if isinstance(cell.value, float):
                if header.endswith(("_rate", "_share", "lift")) or header.startswith("Q+"):
                    cell.number_format = "0.0%" if not header.endswith("lift") else "0.00"
                else:
                    cell.number_format = "#,##0.00"


def main() -> None:
    """Build the workbook."""
    setup_logging()
    cfg = load_config()
    sheets = build_sheets(cfg)
    path = project_path("reports/summary.xlsx")
    path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        for name, table in sheets.items():
            table.to_excel(writer, sheet_name=name, index=False)
            format_sheet(writer.sheets[name])
            logger.info("%-18s %4d rows", name, len(table))
    logger.info("Wrote %s", path.relative_to(project_path(".")))


if __name__ == "__main__":
    main()
